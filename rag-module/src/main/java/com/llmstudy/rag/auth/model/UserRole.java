package com.llmstudy.rag.auth.model;

/**
 * 系统内置用户角色。
 *
 * <p>角色用于表达用户的管理级别；具体资源是否可访问，仍应结合资源所有者、
 * 所属组织和可见范围，通过对应的访问策略判断。</p>
 */
public enum UserRole {
    /** 普通用户，只能管理自己的资源。 */
    USER,
    /** 组织管理员，可管理本组织内标记为组织可见的文档。 */
    ORG_ADMIN,
    /** 系统管理员，可执行系统维护操作并管理文档，但不能越权读取他人聊天。 */
    SYS_ADMIN
}
